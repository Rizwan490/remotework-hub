/* =============================================================================
   8. sitemap.xml
   ========================================================================== */
function buildSitemap(jobs) {
  const today = new Date().toISOString().slice(0, 10);
  const entry = (loc, changefreq, priority, lastmod) =>
    '  <url><loc>' + esc(loc) + '</loc>' +
    (lastmod ? '<lastmod>' + lastmod + '</lastmod>' : '') +
    '<changefreq>' + changefreq + '</changefreq><priority>' + priority + '</priority></url>';

  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!--',
    '  Generated by tools/build.js on ' + today + ' — re-run it after editing',
    '  assets/data/jobs.json or the domain in assets/js/config.js.',
    '-->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    entry(SITE_URL + '/', 'daily', '1.0', today),
    entry(canonicalUrl('jobs.html'), 'daily', '0.9', today),
    entry(canonicalUrl('categories.html'), 'weekly', '0.8', today),
    ''
  ];

  CATEGORIES.forEach((c) => {
    lines.push(entry(canonicalUrl('category.html?category=' + encodeURIComponent(c.slug)), 'daily', '0.7', today));
  });
  lines.push('');

  /* One entry per job page — the reason this script exists. */
  jobs.forEach((job) => {
    lines.push(entry(canonicalUrl(job.pageUrl), 'weekly', '0.8', isoDate(job.postedDate) || today));
  });
  lines.push('');

  ['about.html', 'contact.html'].forEach((p) => lines.push(entry(canonicalUrl(p), 'monthly', '0.5')));
  ['privacy.html', 'terms.html', 'disclaimer.html'].forEach((p) => lines.push(entry(canonicalUrl(p), 'yearly', '0.3')));

  lines.push('</urlset>', '');
  return lines.join('\n');
}

/* =============================================================================
   9. Run
   ========================================================================== */
function main() {
  const raw = JSON.parse(readFile('assets/data/jobs.json'));
  const list = Array.isArray(raw) ? raw : Array.isArray(raw.jobs) ? raw.jobs : [];
  const jobs = list
    .map(normalize)
    .filter((j) => j.status === 'active')
    .sort((a, b) => dateValue(b.postedDate) - dateValue(a.postedDate));

  if (!jobs.length) {
    console.error('! No active listings found in assets/data/jobs.json — nothing to generate.');
    process.exit(1);
  }

  /* Two jobs sharing a slug would overwrite each other's page. */
  const seen = new Map();
  jobs.forEach((j) => {
    if (seen.has(j.slug)) {
      console.error('! Duplicate slug "' + j.slug + '" from ids ' + seen.get(j.slug) + ' and ' + j.id +
        '.\n  Give one of them a unique "id" (or a "slug") in jobs.json and re-run.');
      process.exit(1);
    }
    seen.set(j.slug, j.id);
  });

  const chrome = liftChrome();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const written = new Set();
  jobs.forEach((job) => {
    const file = path.join(ROOT, job.file);
    fs.writeFileSync(file, pageHTML(job, jobs, chrome), 'utf8');
    written.add(path.basename(file));
  });

  /* Remove pages for listings that are gone, but never touch hand-written
     files: only pages carrying this script's marker are deleted. */
  let removed = 0;
  fs.readdirSync(OUT_DIR).forEach((name) => {
    if (!name.endsWith('.html') || written.has(name)) return;
    const full = path.join(OUT_DIR, name);
    if (fs.readFileSync(full, 'utf8').includes(MARKER)) {
      fs.unlinkSync(full);
      removed++;
    }
  });

  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), buildSitemap(jobs), 'utf8');

  /* /remote-jobs/ itself is not a page — send it to the listing page. */
  const redirects = [
    '# Generated by tools/build.js — Cloudflare Pages reads this on deploy.',
    '/' + JOB_DIR + '/    ' + linkPath('/jobs.html') + '    301',
    '/' + JOB_DIR + '     ' + linkPath('/jobs.html') + '    301',
    ''
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, '_redirects'), redirects, 'utf8');

  /* ---- report ---- */
  const noSchema = jobs.filter((j) => !jobPostingSchema(j));
  console.log('\n  ' + jobs.length + ' job page' + (jobs.length === 1 ? '' : 's') + ' written to /' + JOB_DIR + '/');
  if (removed) console.log('  ' + removed + ' page' + (removed === 1 ? '' : 's') + ' removed (listing no longer in jobs.json)');
  console.log('  sitemap.xml rebuilt with ' + (jobs.length + CATEGORIES.length + 8) + ' URLs');
  console.log('  _redirects written');
  console.log('\n  Example URL: ' + canonicalUrl(jobs[0].pageUrl));

  if (SITE_URL.includes('YOUR-DOMAIN')) {
    console.log('\n  ! assets/js/config.js still points at ' + SITE_URL);
    console.log('    Set your real domain there, then run this script again so the');
    console.log('    canonical tags and sitemap.xml carry the right host.');
  }
  if (SITE_CONFIG.demoMode) {
    console.log('\n  ! demoMode is true, so every generated page is noindex, nofollow.');
    console.log('    Set demoMode: false in assets/js/config.js once the listings are real.');
  }
  if (noSchema.length) {
    console.log('\n  ! ' + noSchema.length + ' page(s) have no JobPosting structured data because the');
    console.log('    listing is marked "demo": true (or is missing title/company/postedDate).');
    console.log('    Google must not be given markup for jobs that do not exist — remove the');
    console.log('    demo flag once the entry is a verified vacancy.');
  }
  console.log('');
}

main();
