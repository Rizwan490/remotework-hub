/* =============================================================================
   5. Page chrome — lifted from job.html so the generated pages never drift
   ========================================================================== */
function liftChrome() {
  const src = readFile('job.html');
  const headerStart = src.indexOf('<a class="skip-link"');
  const mainStart = src.indexOf('<main id="main">');
  const mainEnd = src.indexOf('</main>');
  const scriptStart = src.indexOf('<script src="assets/js/config.js"');
  if (headerStart < 0 || mainStart < 0 || mainEnd < 0 || scriptStart < 0) {
    throw new Error('job.html no longer has the expected structure — update tools/build.js.');
  }
  const footerStart = src.indexOf('<footer class="site-footer">');
  return {
    header: rewritePaths(src.slice(headerStart, mainStart)),
    footer: rewritePaths(src.slice(footerStart, scriptStart)),
    scripts: rewritePaths(src.slice(scriptStart, src.indexOf('</body>')))
  };
}

/* The generated pages sit one folder down, so same-folder links need ../ */
function rewritePaths(html) {
  return html.replace(/(href|src)="(?!https?:|\/\/|\/|#|\.\.\/|mailto:|tel:|data:)([^"]+)"/g, (m, attr, url) => attr + '="../' + url + '"');
}

