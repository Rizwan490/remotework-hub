#!/usr/bin/env node
/* =============================================================================
   tools/build.js — static page generator
   -----------------------------------------------------------------------------
   Turns every listing in assets/data/jobs.json into its own crawlable HTML
   page so each job has a unique, indexable URL:

       /remote-jobs/<slug>.html

   It also rewrites sitemap.xml so those URLs are submitted to search engines.

   Run it after every change to jobs.json:

       node tools/build.js

   Nothing is installed and nothing is bundled — this only writes HTML.
   Branding, domain, categories and the output folder all come from
   assets/js/config.js, which stays the single source of truth.
   ========================================================================== */

'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const MARKER = '<!-- Generated by tools/build.js — edits here are overwritten. -->';

/* =============================================================================
   1. Load config.js and app.js without duplicating their contents
   ========================================================================== */
function readFile(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

function loadConfig() {
  const code = readFile('assets/js/config.js');
  const sandbox = {};
  vm.runInNewContext(
    code + '\n;globalThis.__exports = { SITE_CONFIG, CATEGORIES };',
    sandbox,
    { filename: 'config.js' }
  );
  return sandbox.__exports;
}

/** Reuse the icon set from app.js so generated markup matches the live UI. */
function loadIcons() {
  const code = readFile('assets/js/app.js');
  const match = code.match(/const ICONS = (\{[\s\S]*?\n {2}\});/);
  if (!match) {
    console.warn('! Could not read ICONS from app.js — icons will be added by JS only.');
    return {};
  }
  try {
    return vm.runInNewContext('(' + match[1] + ')');
  } catch (err) {
    console.warn('! ICONS block in app.js could not be parsed:', err.message);
    return {};
  }
}

const { SITE_CONFIG, CATEGORIES } = loadConfig();
const ICONS = loadIcons();

const SITE_URL = String(SITE_CONFIG.url || '').replace(/\/+$/, '');
const JOB_DIR = String((SITE_CONFIG.jobPages && SITE_CONFIG.jobPages.dir) || 'remote-jobs')
  .replace(/^\/+|\/+$/g, '');
const CLEAN_URLS = !!(SITE_CONFIG.seo && SITE_CONFIG.seo.cleanUrls);
const OUT_DIR = path.join(ROOT, JOB_DIR);

/* =============================================================================
   2. Small helpers — ports of the matching functions in app.js / jobs.js
   ========================================================================== */
const ENT = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const esc = (v) => (v === null || v === undefined ? '' : String(v).replace(/[&<>"']/g, (c) => ENT[c]));

function slugify(str) {
  return String(str).toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function truncate(str, max) {
  const s = String(str || '').trim();
  if (s.length <= max) return s;
  return s.slice(0, max - 1).replace(/\s+\S*$/, '') + '…';
}

function initials(name) {
  const parts = String(name || '').replace(/[^A-Za-z0-9 ]/g, ' ').split(/\s+/).filter(Boolean);
  if (!parts.length) return '–';
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[1][0]).toUpperCase();
}

function hueFor(name) {
  let h = 0;
  const s = String(name || '');
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 360;
  return h;
}

function formatDate(value) {
  const d = value ? new Date(value) : null;
  if (!d || isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' });
}

function isoDate(value) {
  const d = value ? new Date(value) : null;
  if (!d || isNaN(d.getTime())) return '';
  return d.toISOString().slice(0, 10);
}

function safeUrl(value) {
  if (!value) return '';
  try {
    const u = new URL(String(value));
    return u.protocol === 'http:' || u.protocol === 'https:' ? u.href : '';
  } catch (err) {
    return '';
  }
}

function icon(name, cls) {
  const body = ICONS[name];
  if (!body) return '';
  return '<svg class="icon' + (cls ? ' ' + cls : '') + '" viewBox="0 0 24 24" aria-hidden="true" focusable="false">' + body + '</svg>';
}

const asArray = (v) => (Array.isArray(v) ? v.filter((x) => typeof x === 'string' && x.trim()) : []);

/* Root-relative path -> path usable from inside the job folder. */
const up = (p) => '../' + String(p || '').replace(/^\/+/, '');
const absUrl = (p) => SITE_URL + '/' + String(p || '').replace(/^\/+/, '');

/* The address search engines should index. Cloudflare Pages serves every page
   without its .html and redirects /jobs.html -> /jobs, so pointing a canonical
   at the .html would point it at a redirect. Links inside the site keep the
   .html — they still work when the folder is opened locally. */
function canonicalUrl(p) {
  let out = String(p || '').replace(/^\/+/, '');
  if (CLEAN_URLS) {
    out = out.replace(/\.html(?=$|[?#])/, '');
    if (out === 'index' || out.indexOf('index?') === 0) out = out.slice(5);
  }
  return absUrl(out);
}

/* Root-relative link path, .html kept (used for hrefs and for _redirects). */
const linkPath = (p) => (CLEAN_URLS ? String(p).replace(/\.html(?=$|[?#])/, '') : String(p));

/* =============================================================================
   3. Normalise listings — mirrors Jobs.normalize() in assets/js/jobs.js
   ========================================================================== */
function jobSlug(job) {
  if (job.slug) return slugify(job.slug).slice(0, 120);
  const title = slugify(job.title).slice(0, 70).replace(/-+$/, '');
  const company = slugify(job.company).slice(0, 40).replace(/-+$/, '');
  const id = slugify(job.id);
  return [title, company ? 'at-' + company : '', id].filter(Boolean).join('-');
}

function normalize(raw, index) {
  const job = {
    id: String(raw.id || '').trim() || 'job-' + index,
    demo: raw.demo === true,
    title: String(raw.title || 'Untitled role').trim(),
    company: String(raw.company || 'Undisclosed company').trim(),
    companyLogo: safeUrl(raw.companyLogo),
    location: String(raw.location || '').trim(),
    country: String(raw.country || '').trim(),
    remote: raw.remote !== false,
    jobType: String(raw.jobType || '').trim(),
    category: slugify(raw.category || 'other'),
    experience: String(raw.experience || '').trim(),
    salary: String(raw.salary || '').trim(),
    salaryMin: Number(raw.salaryMin) || 0,
    salaryMax: Number(raw.salaryMax) || 0,
    salaryCurrency: String(raw.salaryCurrency || '').trim(),
    salaryPeriod: String(raw.salaryPeriod || '').trim().toUpperCase(),
    postedDate: String(raw.postedDate || '').trim(),
    validThrough: String(raw.validThrough || '').trim(),
    description: String(raw.description || '').trim(),
    responsibilities: asArray(raw.responsibilities),
    requirements: asArray(raw.requirements),
    benefits: asArray(raw.benefits),
    skills: asArray(raw.skills),
    applyUrl: safeUrl(raw.applyUrl),
    source: String(raw.source || '').trim(),
    featured: raw.featured === true,
    status: String(raw.status || 'active').trim().toLowerCase(),
    slug: String(raw.slug || '').trim()
  };
  job.slug = jobSlug(job);
  job.pageUrl = JOB_DIR + '/' + job.slug + '.html'; // the file, and every href
  job.file = job.pageUrl;
  return job;
}

function categoryMeta(slug) {
  return (
    CATEGORIES.find((c) => c.slug === slug) || {
      slug: slug,
      name: slug ? slug.replace(/-/g, ' ').replace(/\b\w/g, (m) => m.toUpperCase()) : 'Other',
      icon: 'briefcase',
      blurb: '',
      intro: ''
    }
  );
}

/** Same scoring as Jobs.related() so the static block matches the live one. */
function relatedJobs(all, job, limit) {
  const skills = new Set(job.skills.map((s) => s.toLowerCase()));
  return all
    .filter((j) => j.id !== job.id)
    .map((j) => {
      let score = 0;
      if (j.category === job.category) score += 50;
      if (j.jobType === job.jobType) score += 12;
      if (j.experience === job.experience) score += 6;
      if (j.country === job.country) score += 4;
      j.skills.forEach((s) => {
        if (skills.has(s.toLowerCase())) score += 8;
      });
      return { job: j, score: score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || dateValue(b.job.postedDate) - dateValue(a.job.postedDate))
    .slice(0, limit || SITE_CONFIG.listing.relatedJobs)
    .map((x) => x.job);
}

function dateValue(v) {
  const d = v ? new Date(v) : null;
  return d && !isNaN(d.getTime()) ? d.getTime() : 0;
}

/* =============================================================================
   4. Structured data (JSON-LD)
   ========================================================================== */
/** Google asks for the description in HTML — lists included. */
function schemaDescription(job) {
  const block = (heading, items) =>
    items.length
      ? '<h3>' + esc(heading) + '</h3><ul>' + items.map((i) => '<li>' + esc(i) + '</li>').join('') + '</ul>'
      : '';
  return (
    '<p>' + esc(job.description) + '</p>' +
    block('Responsibilities', job.responsibilities) +
    block('Requirements', job.requirements) +
    block('Benefits', job.benefits)
  );
}

/* A JobPosting is only emitted for real listings. Sample/demo rows and every
   missing field are left out rather than invented — fabricated job markup is
   a structured-data violation and gets sites penalised. */
function jobPostingSchema(job) {
  if (!SITE_CONFIG.features.structuredData) return null;
  if (SITE_CONFIG.demoMode || job.demo) return null;
  if (!job.title || !job.company || !job.postedDate) return null;

  const data = {
    '@context': 'https://schema.org',
    '@type': 'JobPosting',
    title: job.title,
    description: schemaDescription(job),
    datePosted: job.postedDate,
    url: canonicalUrl(job.pageUrl),
    hiringOrganization: { '@type': 'Organization', name: job.company },
    identifier: { '@type': 'PropertyValue', name: job.company, value: job.id }
  };

  if (job.validThrough) data.validThrough = job.validThrough;
  if (job.jobType) {
    const map = {
      'full-time': 'FULL_TIME',
      'part-time': 'PART_TIME',
      contract: 'CONTRACTOR',
      freelance: 'CONTRACTOR',
      internship: 'INTERN',
      temporary: 'TEMPORARY'
    };
    const key = job.jobType.toLowerCase();
    if (map[key]) data.employmentType = map[key];
  }
  if (job.companyLogo) data.hiringOrganization.logo = job.companyLogo;

  if (job.remote) {
    data.jobLocationType = 'TELECOMMUTE';
    if (job.country && job.country !== 'Worldwide') {
      data.applicantLocationRequirements = { '@type': 'Country', name: job.country };
    }
  } else if (job.country) {
    data.jobLocation = {
      '@type': 'Place',
      address: { '@type': 'PostalAddress', addressCountry: job.country }
    };
  }

  if (job.salaryMin > 0 && job.salaryCurrency && job.salaryPeriod) {
    const value = { '@type': 'QuantitativeValue', unitText: job.salaryPeriod };
    if (job.salaryMax > job.salaryMin) {
      value.minValue = job.salaryMin;
      value.maxValue = job.salaryMax;
    } else {
      value.value = job.salaryMin;
    }
    data.baseSalary = { '@type': 'MonetaryAmount', currency: job.salaryCurrency, value: value };
  }

  if (job.skills.length) data.skills = job.skills.join(', ');
  if (job.requirements.length) data.qualifications = job.requirements.join(' ');
  if (job.responsibilities.length) data.responsibilities = job.responsibilities.join(' ');
  if (job.benefits.length) data.jobBenefits = job.benefits.join(' ');
  if (job.experience) data.experienceRequirements = job.experience;
  if (job.category) data.occupationalCategory = categoryMeta(job.category).name;
  if (job.applyUrl) data.directApply = false; // the employer's site takes the application

  return data;
}

function breadcrumbSchema(job) {
  const cat = categoryMeta(job.category);
  const items = [
    ['Home', canonicalUrl('index.html')],
    ['Remote Jobs', canonicalUrl('jobs.html')],
    [cat.name, canonicalUrl('category.html?category=' + encodeURIComponent(cat.slug))],
    [job.title + ' at ' + job.company, canonicalUrl(job.pageUrl)]
  ];
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map((pair, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: pair[0],
      item: pair[1]
    }))
  };
}

