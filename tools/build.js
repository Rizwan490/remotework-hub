function logoHTML(job, size) {
  const cls = 'company-logo' + (size ? ' company-logo--' + size : '');
  if (job.companyLogo) {
    return '<img class="' + cls + '" src="' + esc(job.companyLogo) + '" alt="' + esc(job.company + ' logo') +
      '" loading="lazy" decoding="async" width="56" height="56">';
  }
  return '<span class="' + cls + '" style="--logo-hue:' + hueFor(job.company) + '" aria-hidden="true">' +
    esc(initials(job.company)) + '</span>';
}

function metaHTML(job) {
  const items = [];
  if (job.location) items.push(['pin', job.location]);
  if (job.jobType) items.push(['briefcase', job.jobType]);
  if (job.salary) items.push(['wallet', job.salary]);
  return '<ul class="meta-list">' + items
    .map((it) => '<li class="meta-list__item">' + icon(it[0]) + '<span>' + esc(it[1]) + '</span></li>')
    .join('') + '</ul>';
}

function saveButtonHTML(job, variant) {
  if (!SITE_CONFIG.features.savedJobs) return '';
  const cls = 'save-btn' + (variant ? ' save-btn--' + variant : '');
  return '<button type="button" class="' + cls + '" data-save-job="' + esc(job.id) + '" aria-pressed="false"' +
    ' aria-label="' + esc('Save job: ' + job.title) + '">' + icon('bookmark') +
    (variant === 'wide' ? '<span class="save-btn__text">Save Job</span>' : '') + '</button>';
}

function applyButtonHTML(job, extraClass) {
  const cls = 'btn btn--primary ' + (extraClass || 'btn--lg') + ' btn--apply';
  if (job.applyUrl) {
    return '<a class="' + cls + '" href="' + esc(job.applyUrl) + '" target="_blank" rel="noopener noreferrer nofollow">' +
      'Apply on Employer Website' + icon('external') + '</a>';
  }
  return '<button type="button" class="' + cls + '" disabled aria-disabled="true">Application link unavailable</button>';
}

function applyBlockHTML(job, compact) {
  const note = job.applyUrl
    ? 'This button opens the employer’s own application page in a new tab. ' + SITE_CONFIG.name +
      ' is not the employer and does not collect applications.'
    : 'This is a sample listing used to demonstrate the site. There is no application link and no vacancy behind it.';
  return (
    (compact
      ? '<h2 class="side-card__title">Apply for this job</h2>'
      : '<h2 class="detail-block__title">How to apply</h2>') +
    applyButtonHTML(job) +
    '<p class="apply-note">' + esc(note) + '</p>'
  );
}

function listBlock(title, items) {
  if (!items.length) return '';
  return '<section class="detail-block">' +
    '<h2 class="detail-block__title">' + esc(title) + '</h2>' +
    '<ul class="tick-list">' +
      items.map((i) => '<li>' + icon('check') + '<span>' + esc(i) + '</span></li>').join('') +
    '</ul>' +
  '</section>';
}

